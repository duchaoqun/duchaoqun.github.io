// 调色板条渲染到卡片上
function renderPaletteBar(canvas, palette) {
  var ctx = canvas.getContext('2d');
  var w = canvas.width, h = canvas.height;
  var colors = PALETTES[palette] || [];
  if (palette === 'auto') {
    // 彩虹条
    for (var i = 0; i < w; i++) {
      var hue = (i / w) * 280 + 180; // 从红→蓝紫
      ctx.fillStyle = 'hsl(' + hue + ', 70%, 55%)';
      ctx.fillRect(i, 0, 1, h);
    }
    return;
  }
  if (palette === 'fromimage') {
    // 彩虹 + 描述用
    for (var i = 0; i < w; i++) {
      var hue2 = (i / w) * 300;
      ctx.fillStyle = 'hsl(' + hue2 + ', 60%, 50%)';
      ctx.fillRect(i, 0, 1, h);
    }
    return;
  }
  var step = w / Math.max(1, colors.length);
  for (var j = 0; j < colors.length; j++) {
    var c = colors[j];
    ctx.fillStyle = 'rgb(' + c[0] + ',' + c[1] + ',' + c[2] + ')';
    ctx.fillRect(Math.floor(j * step), 0, Math.ceil(step), h);
  }
}
